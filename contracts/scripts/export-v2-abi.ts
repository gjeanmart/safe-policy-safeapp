import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

/**
 * Writes `src/lib/v2/abi.ts` (the app's V2 ABIs, `as const`) from the compiled WP0 interfaces, so
 * the TypeScript mirror cannot drift from the Solidity. Run `pnpm export:v2-abi` in `contracts/`
 * (compiles first) after changing any V2 interface, then `pnpm format` at the root.
 */

type AbiItem = { type: string; name?: string; inputs?: { type: string; internalType?: string }[] }

const OUT = resolve(__dirname, '../../src/lib/v2/abi.ts')
const ARTIFACTS = resolve(__dirname, '../artifacts/contracts')

/** Path of every compiled artifact by contract name (names are unique in this package). */
function artifactPaths(dir: string, found = new Map<string, string>()): Map<string, string> {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) artifactPaths(path, found)
    else if (entry.name.endsWith('.json') && !entry.name.endsWith('.dbg.json'))
      found.set(entry.name.slice(0, -5), path)
  }
  return found
}

const targets: [name: string, contracts: string[], doc: string][] = [
  [
    'policyEngineV2Abi',
    ['IPolicyEngineV2', 'IERC165'],
    'Engine API: configuration, freeze, enumeration, preview.',
  ],
  ['policyV2Abi', ['IPolicyV2'], 'What the engine calls on every policy.'],
  ['policySignLibAbi', ['IPolicySignLib'], 'DELEGATECALL target for on-chain ERC-1271 approvals.'],
  [
    'policyFallbackHandlerAbi',
    ['IPolicyFallbackHandler'],
    'Fallback handler accepting on-chain approvals only.',
  ],
  ['freezePolicyAbi', ['IFreezePolicy'], 'FreezePolicy views and settings.'],
  ['timelockPolicyAbi', ['ITimelockPolicy'], 'TimelockPolicy schedule / cancel / views.'],
  ['recipientsPolicyAbi', ['IRecipientsPolicy'], 'RecipientsPolicy views and settings.'],
  ['limitPolicyAbi', ['ILimitPolicy'], 'LimitPolicy views and settings.'],
  ['argsPolicyAbi', ['IArgsPolicy'], 'ArgsPolicy views and settings.'],
  ['coSignerPolicyV2Abi', ['ICoSignerPolicyV2'], 'CoSignerPolicyV2 module-path proofs, views and settings.'],
  ['safenetPolicyV2Abi', ['ISafenetPolicyV2'], 'SafenetPolicyV2 module-path proofs and views.'],
  ['quorumPolicyV2Abi', ['IQuorumPolicyV2'], 'QuorumPolicyV2 views and settings.'],
]

// Every custom error a V2 check can surface, directly or as `PolicyDenied.reason`.
const ERROR_SOURCES = [
  'IPolicyEngineV2',
  'PolicyBaseV2',
  'SignatureExtension',
  'IFreezePolicy',
  'ITimelockPolicy',
  'IRecipientsPolicy',
  'ILimitPolicy',
  'IArgsPolicy',
  'ICoSignerPolicyV2',
  'ISafenetPolicyV2',
  'IQuorumPolicyV2',
]

const signature = (item: AbiItem) =>
  `${item.type} ${item.name ?? ''}(${(item.inputs ?? []).map((i) => i.internalType ?? i.type).join(',')})`

function abiOf(names: string[]): AbiItem[] {
  const paths = artifactPaths(ARTIFACTS)
  const seen = new Set<string>()
  const items: AbiItem[] = []
  for (const name of names) {
    const path = paths.get(name)
    if (!path) throw new Error(`no artifact for ${name}: run \`pnpm build\` first`)
    for (const item of JSON.parse(readFileSync(path, 'utf8')).abi as AbiItem[]) {
      const sig = signature(item)
      if (!seen.has(sig)) {
        seen.add(sig)
        items.push(item)
      }
    }
  }
  return items
}

function main() {
  const parts = [
    '// Generated by contracts/scripts/export-v2-abi.ts from the compiled V2 interfaces. Do not edit:',
    '// change the Solidity, run `pnpm export:v2-abi` in contracts/, then `pnpm format` at the root.',
    '',
  ]
  for (const [name, contracts, doc] of targets) {
    parts.push(`/** ${doc} (${contracts.join(' + ')}) */`)
    parts.push(`export const ${name} = ${JSON.stringify(abiOf(contracts))} as const`, '')
  }
  const errors = abiOf(ERROR_SOURCES).filter((item) => item.type === 'error')
  parts.push(
    '/** Every V2 custom error (engine, policy base, policies), for decoding reverts and `PolicyDenied` reasons. */',
  )
  parts.push(`export const policyV2ErrorsAbi = ${JSON.stringify(errors)} as const`, '')
  writeFileSync(OUT, parts.join('\n'))
  console.log(`wrote ${OUT}`)
}

main()
