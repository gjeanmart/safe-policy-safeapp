import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

/**
 * Writes `src/lib/v2/abi.ts` (the app's V2 ABIs, `as const`) from the compiled V2 interfaces, so
 * the TypeScript mirror cannot drift from the Solidity. Run `pnpm export:v2-abi` in `contracts/`
 * (compiles first) after changing any V2 interface, then `pnpm format` at the root.
 */

type AbiItem = { type: string; name?: string; inputs?: { type: string; internalType?: string }[] }

const OUT = resolve(__dirname, '../../src/lib/v2/abi.ts')
const ARTIFACTS = resolve(__dirname, '../artifacts/contracts')

/** Path of every compiled artifact by contract name, the v2 one winning a name clash. */
function artifactPaths(dir: string, found = new Map<string, string>()): Map<string, string> {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) artifactPaths(path, found)
    else if (entry.name.endsWith('.json') && !entry.name.endsWith('.dbg.json')) {
      const name = entry.name.slice(0, -5)
      // Prefer the v2 artifact when names clash (the vendored V1 engine has its own IPolicy, ISafe, ...).
      if (!found.has(name) || path.includes('/v2/')) found.set(name, path)
    }
  }
  return found
}

const targets: [name: string, contracts: string[], doc: string][] = [
  ['policyGuardAbi', ['IPolicyGuard'], 'The engine: hooks, configure, views, matches, ERC-165.'],
  ['policyAbi', ['IPolicy'], 'What the engine calls on every policy (configure, check, validate).'],
  ['timelockPolicyAbi', ['ITimelockPolicy'], 'TimelockPolicy: schedule, cancel, freeze, lift, views.'],
  ['argsPolicyAbi', ['IArgsPolicy'], 'ArgsPolicy: settings and views.'],
  ['limitPolicyAbi', ['ILimitPolicy'], 'LimitPolicy: settings, remaining budget.'],
  ['coSignerPolicyAbi', ['ICoSignerPolicy'], 'CoSignerPolicy: approve, approveWithSig, revoke, views.'],
  ['safenetPolicyAbi', ['ISafenetPolicy'], 'SafenetPolicy: submitAttestation, views.'],
]

// Every custom error a check can surface, directly or as `PolicyDenied.reason`.
const ERROR_SOURCES = [
  'IPolicyGuard',
  'PolicyBase',
  'ITimelockPolicy',
  'TimelockPolicyQueue',
  'IArgsPolicy',
  'ILimitPolicy',
  'ICoSignerPolicy',
  'ISafenetPolicy',
  'FROST',
  'Secp256k1',
  'EpochRollover',
]

const signature = (item: AbiItem) =>
  `${item.type} ${item.name ?? ''}(${(item.inputs ?? []).map((i) => i.internalType ?? i.type).join(',')})`

function abiOf(names: string[]): AbiItem[] {
  const paths = artifactPaths(ARTIFACTS)
  const seen = new Set<string>()
  const items: AbiItem[] = []
  for (const name of names) {
    const path = paths.get(name)
    if (!path) throw new Error(`no artifact for ${name}: run \`pnpm build\` first`)
    for (const item of JSON.parse(readFileSync(path, 'utf8')).abi as AbiItem[]) {
      const sig = signature(item)
      if (!seen.has(sig)) {
        seen.add(sig)
        items.push(item)
      }
    }
  }
  return items
}

function main() {
  const parts = [
    '// Generated by contracts/scripts/export-v2-abi.ts from the compiled V2 interfaces. Do not edit:',
    '// change the Solidity, run `pnpm export:v2-abi` in contracts/, then `pnpm format` at the root.',
    '',
  ]
  for (const [name, contracts, doc] of targets) {
    parts.push(`/** ${doc} (${contracts.join(' + ')}) */`)
    parts.push(`export const ${name} = ${JSON.stringify(abiOf(contracts))} as const`, '')
  }
  const errors = abiOf(ERROR_SOURCES).filter((item) => item.type === 'error')
  parts.push(
    '/** Every V2 custom error (engine, policy base, policies, FROST), to decode reverts and `PolicyDenied` reasons. */',
  )
  parts.push(`export const policyErrorsAbi = ${JSON.stringify(errors)} as const`, '')
  writeFileSync(OUT, parts.join('\n'))
  console.log(`wrote ${OUT}`)
}

main()
